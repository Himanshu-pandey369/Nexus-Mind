import axios from "axios";
import { graph } from "../graph/graph.js";

const CHAT_SERVICE_URL = process.env.CHAT_SERVICE_URL;

/**
 * POST /agent/chat
 * Body: { prompt: string, conversationId: string }
 */
export const agentChat = async (req, res) => {
  const { prompt, conversationId } = req.body;

  // --- Input validation ---
  if (!prompt || typeof prompt !== "string" || prompt.trim() === "") {
    return res.status(400).json({
      success: false,
      message: "prompt is required and must be a non-empty string",
    });
  }

  if (
    !conversationId ||
    typeof conversationId !== "string" ||
    conversationId.trim() === ""
  ) {
    return res.status(400).json({
      success: false,
      message: "conversationId is required and must be a non-empty string",
    });
  }

  // --- Persist user message to Chat Service ---
  try {
    await axios.post(
      `${CHAT_SERVICE_URL}/chat/conversations/${conversationId}/messages`,
      { role: "user", content: prompt }
    );
  } catch (err) {
    const status = err.response?.status;
    const msg = err.response?.data?.message || err.message;
    console.error(`[Agent Controller] Failed to save user message: ${msg}`);

    // Return a clear error; do not proceed if the message cannot be persisted
    return res.status(502).json({
      success: false,
      message: "Failed to save message to Chat Service",
    });
  }

  // --- Invoke the LangGraph workflow ---
  let result;
  try {
    result = await graph.invoke({ prompt: prompt.trim(), conversationId });
  } catch (err) {
    console.error("[Agent Controller] Graph invocation error:", err.message);
    return res.status(500).json({
      success: false,
      message: "AI processing failed. Please try again.",
    });
  }

  const aiResponse = result?.aiResponse;

  if (!aiResponse) {
    console.error("[Agent Controller] Graph returned no aiResponse");
    return res.status(500).json({
      success: false,
      message: "No response generated by the AI agent",
    });
  }

  return res.status(200).json({
    success: true,
    aiResponse,
  });
};
