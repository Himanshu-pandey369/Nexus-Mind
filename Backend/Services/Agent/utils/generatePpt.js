import { createRequire } from "module";

// pptxgenjs ships a CJS bundle; we require() it from an ESM module context.
const require = createRequire(import.meta.url);
const PptxGenJS = require("pptxgenjs");

// ── Design tokens ──────────────────────────────────────────────────────────────

const COLORS = {
  // Primary dark navy – used for cover / thank-you backgrounds
  bgDark:    "1a1a2e",
  // Medium indigo accent used for divider bars and highlights
  accent:    "5c5ce0",
  // Light accent for content slide backgrounds
  bgSlide:   "f0f0f8",
  // Text on dark slides
  textLight: "f0f0f8",
  // Text on light slides
  textDark:  "1a1a2e",
  // Subtitle / muted text on dark slides
  muted:     "9090b8",
  // Bullet dot on content slides
  bullet:    "5c5ce0",
  // Footer text
  footer:    "9090b8",
  // White
  white:     "ffffff",
};

const FONTS = {
  heading: "Calibri",
  body:    "Calibri",
};

// Slide canvas (LAYOUT_WIDE = 13.33 × 7.5 inches)
const W = 13.33;
const H = 7.5;

// ── Helpers ───────────────────────────────────────────────────────────────────

/**
 * Add a full-bleed coloured background rectangle to a slide.
 */
function addBackground(ppt, slide, color) {
  slide.addShape(ppt.ShapeType.rect, {
    x: 0, y: 0, w: W, h: H,
    fill: { color },
    line: { color, width: 0 },
  });
}

/**
 * Add a narrow horizontal accent bar.
 */
function addAccentBar(ppt, slide, opts = {}) {
  const { x = 0, y = H - 0.12, w = W, h = 0.12, color = COLORS.accent } = opts;
  slide.addShape(ppt.ShapeType.rect, { x, y, w, h, fill: { color }, line: { color, width: 0 } });
}

/**
 * Truncate a point string to a safe display length.
 */
function truncate(str, max = 160) {
  if (!str || str.length <= max) return str;
  return str.slice(0, max - 1) + "…";
}

// ── Cover Slide ───────────────────────────────────────────────────────────────

function addCoverSlide(ppt, data) {
  const slide = ppt.addSlide();

  // Full-bleed dark background
  addBackground(ppt, slide, COLORS.bgDark);

  // Decorative left accent strip
  slide.addShape(ppt.ShapeType.rect, {
    x: 0, y: 0, w: 0.3, h: H,
    fill: { color: COLORS.accent },
    line: { color: COLORS.accent, width: 0 },
  });

  // Bottom accent bar
  addAccentBar(ppt, slide, { x: 0, y: H - 0.2, w: W, h: 0.2, color: COLORS.accent });

  // Presentation title
  slide.addText(data.title, {
    x: 1.2, y: 1.8, w: W - 2.4, h: 1.4,
    fontSize: 40,
    bold: true,
    color: COLORS.textLight,
    fontFace: FONTS.heading,
    align: "center",
    valign: "middle",
    wrap: true,
  });

  // Subtitle
  if (data.subtitle) {
    slide.addText(data.subtitle, {
      x: 1.2, y: 3.5, w: W - 2.4, h: 0.9,
      fontSize: 20,
      color: COLORS.muted,
      fontFace: FONTS.body,
      align: "center",
      valign: "middle",
      wrap: true,
    });
  }

  // Thin divider line between subtitle and branding
  slide.addShape(ppt.ShapeType.rect, {
    x: 3, y: 5.0, w: W - 6, h: 0.03,
    fill: { color: COLORS.accent },
    line: { color: COLORS.accent, width: 0 },
  });

  // Branding text
  slide.addText("Generated by NexusMind AI", {
    x: 1.2, y: 5.3, w: W - 2.4, h: 0.5,
    fontSize: 13,
    color: COLORS.muted,
    fontFace: FONTS.body,
    align: "center",
    italic: true,
  });
}

// ── Content Slides ────────────────────────────────────────────────────────────

function addContentSlide(ppt, slide_data, index, total) {
  const slide = ppt.addSlide();

  // Light background
  addBackground(ppt, slide, COLORS.bgSlide);

  // Left accent strip (narrow)
  slide.addShape(ppt.ShapeType.rect, {
    x: 0, y: 0, w: 0.15, h: H,
    fill: { color: COLORS.accent },
    line: { color: COLORS.accent, width: 0 },
  });

  // Slide header background strip
  slide.addShape(ppt.ShapeType.rect, {
    x: 0.15, y: 0, w: W - 0.15, h: 1.15,
    fill: { color: COLORS.bgDark },
    line: { color: COLORS.bgDark, width: 0 },
  });

  // Slide title
  slide.addText(slide_data.title, {
    x: 0.5, y: 0.1, w: W - 1.0, h: 0.95,
    fontSize: 24,
    bold: true,
    color: COLORS.textLight,
    fontFace: FONTS.heading,
    valign: "middle",
    wrap: true,
  });

  // Horizontal divider
  slide.addShape(ppt.ShapeType.rect, {
    x: 0.5, y: 1.25, w: W - 1.0, h: 0.04,
    fill: { color: COLORS.accent },
    line: { color: COLORS.accent, width: 0 },
  });

  // Bullet points — cap at 6 to prevent overflow
  const points = slide_data.points.slice(0, 6);
  const pointSpacing = Math.min(0.8, (H - 2.4) / Math.max(points.length, 1));

  points.forEach((point, i) => {
    const yPos = 1.45 + i * pointSpacing;

    // Accent bullet dot
    slide.addShape(ppt.ShapeType.ellipse, {
      x: 0.5, y: yPos + 0.12, w: 0.12, h: 0.12,
      fill: { color: COLORS.bullet },
      line: { color: COLORS.bullet, width: 0 },
    });

    // Point text
    slide.addText(truncate(point.trim()), {
      x: 0.75, y: yPos, w: W - 1.5, h: pointSpacing,
      fontSize: 15,
      color: COLORS.textDark,
      fontFace: FONTS.body,
      valign: "top",
      wrap: true,
    });
  });

  // Footer bar
  addAccentBar(ppt, slide, { x: 0, y: H - 0.3, w: W, h: 0.3, color: COLORS.bgDark });

  // Footer text — left: branding | right: slide number
  slide.addText("NexusMind AI", {
    x: 0.3, y: H - 0.28, w: 4, h: 0.26,
    fontSize: 9,
    color: COLORS.muted,
    fontFace: FONTS.body,
    valign: "middle",
  });

  slide.addText(`${index + 1} / ${total}`, {
    x: W - 1.5, y: H - 0.28, w: 1.2, h: 0.26,
    fontSize: 9,
    color: COLORS.muted,
    fontFace: FONTS.body,
    align: "right",
    valign: "middle",
  });
}

// ── Thank-You Slide ───────────────────────────────────────────────────────────

function addThankYouSlide(ppt) {
  const slide = ppt.addSlide();

  // Dark background
  addBackground(ppt, slide, COLORS.bgDark);

  // Top and bottom accent bars
  addAccentBar(ppt, slide, { x: 0, y: 0,        w: W, h: 0.2, color: COLORS.accent });
  addAccentBar(ppt, slide, { x: 0, y: H - 0.2,  w: W, h: 0.2, color: COLORS.accent });

  // Centred accent ellipse decoration
  slide.addShape(ppt.ShapeType.ellipse, {
    x: W / 2 - 1, y: H / 2 - 1.2, w: 2, h: 2,
    fill: { color: COLORS.accent, transparency: 80 },
    line: { color: COLORS.accent, width: 0 },
  });

  // "Thank You" heading
  slide.addText("Thank You", {
    x: 1, y: 2.2, w: W - 2, h: 1.8,
    fontSize: 52,
    bold: true,
    color: COLORS.textLight,
    fontFace: FONTS.heading,
    align: "center",
    valign: "middle",
  });

  // Sub-line
  slide.addText("Generated by NexusMind AI", {
    x: 1, y: 4.5, w: W - 2, h: 0.6,
    fontSize: 15,
    color: COLORS.muted,
    fontFace: FONTS.body,
    align: "center",
    italic: true,
  });
}

// ── Main export ───────────────────────────────────────────────────────────────

/**
 * Generate a professional PowerPoint presentation from validated JSON data.
 *
 * @param {{ title: string, subtitle: string, slides: Array<{ title: string, points: string[] }> }} data
 * @returns {Promise<Buffer>}  Resolves with the complete PPTX buffer.
 */
export async function generatePpt(data) {
  const { title, subtitle, slides } = data;

  const ppt = new PptxGenJS();

  // Presentation metadata
  ppt.layout  = "LAYOUT_WIDE";   // 16:9
  ppt.title   = title;
  ppt.subject = title;
  ppt.author  = "NexusMind AI";
  ppt.company = "NexusMind AI";
  ppt.lang    = "EN";

  // 1. Cover slide
  addCoverSlide(ppt, { title, subtitle });

  // 2. Content slides
  slides.forEach((slide_data, i) => {
    addContentSlide(ppt, slide_data, i, slides.length);
  });

  // 3. Thank-you slide
  addThankYouSlide(ppt);

  // Generate buffer
  const buffer = await ppt.write({ outputType: "nodebuffer" });

  if (!buffer || buffer.length === 0) {
    throw new Error("pptxgenjs returned an empty buffer");
  }

  return buffer;
}
